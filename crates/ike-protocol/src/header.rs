//! ISAKMP/IKEv2 message header -- 28 bytes, fixed.
//!
//! Both IKE versions share the same 28-byte header layout. The `version`
//! byte distinguishes them: `0x10` for IKEv1 (RFC 2408 section 3.1), `0x20` for
//! IKEv2 (RFC 7296 section 3.1). All multi-byte fields are big-endian.
//!
//! ```text
//! Offset  Size  Field
//! 0       8     Initiator SPI (cookie)
//! 8       8     Responder SPI (cookie)
//! 16      1     Next Payload type
//! 17      1     Version (major << 4 | minor)
//! 18      1     Exchange Type
//! 19      1     Flags
//! 20      4     Message ID
//! 24      4     Length (total, including header)
//! ```

use crate::registry;

/// Fixed size of the ISAKMP/IKEv2 header. RFC 2408 section 3.1 / RFC 7296 section 3.1.
pub const HEADER_LEN: usize = 28;

/// IKE protocol version, encoded as the high nibble of the version byte.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum IkeVersion {
    /// IKEv1 -- version byte `0x10`. RFC 2408.
    V1,
    /// IKEv2 -- version byte `0x20`. RFC 7296.
    V2,
    /// Unrecognised major.minor version.
    Unknown(u8),
}

impl IkeVersion {
    /// Decode from the raw version byte (major in high nibble, minor in low).
    #[must_use]
    pub fn from_byte(b: u8) -> Self {
        match b {
            0x10 => Self::V1,
            0x20 => Self::V2,
            _ => Self::Unknown(b),
        }
    }

    /// Encode to the raw version byte.
    #[must_use]
    pub fn to_byte(self) -> u8 {
        match self {
            Self::V1 => 0x10,
            Self::V2 => 0x20,
            Self::Unknown(b) => b,
        }
    }
}

impl core::fmt::Display for IkeVersion {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::V1 => write!(f, "IKEv1"),
            Self::V2 => write!(f, "IKEv2"),
            Self::Unknown(b) => write!(f, "Unknown({b:#04x})"),
        }
    }
}

registry! {
    /// Exchange types spanning both IKE versions.
    ///
    /// IKEv1: RFC 2408 section 3.1. IKEv2: RFC 7296 section 3.1.
    ExchangeType: u8 {
        /// IKEv1 Base Exchange. Rarely used.
        Base = 1,
        /// IKEv1 Identity Protection (Main Mode) -- 6 messages. RFC 2409 section 5.
        IdentityProtection = 2,
        /// IKEv1 Authentication Only. Rare.
        AuthenticationOnly = 3,
        /// IKEv1 Aggressive Mode -- 3 messages. PSK hash extractable. RFC 2409 section 7.
        Aggressive = 4,
        /// IKEv1 Informational Exchange. RFC 2408 section 5.7.
        Informational = 5,
        /// IKEv1 Quick Mode (Phase 2, encrypted). RFC 2409 section 9.
        QuickMode = 32,
        /// IKEv1 New Group Mode. RFC 2409 section 10.
        NewGroupMode = 33,
        /// IKEv2 IKE_SA_INIT. RFC 7296 section 1.2.
        IkeSaInit = 34,
        /// IKEv2 IKE_AUTH. RFC 7296 section 1.2.
        IkeAuth = 35,
        /// IKEv2 CREATE_CHILD_SA. RFC 7296 section 1.3.
        CreateChildSa = 36,
        /// IKEv2 INFORMATIONAL. RFC 7296 section 1.4.
        Ikev2Informational = 37,
        /// IKEv2 IKE_SESSION_RESUME. RFC 5723.
        IkeSessionResume = 38,
        /// IKEv2 GSA_AUTH (Group Security). RFC 9838.
        GsaAuth = 39,
        /// IKEv2 GSA_REGISTRATION. RFC 9838.
        GsaRegistration = 40,
        /// IKEv2 GSA_REKEY. RFC 9838.
        GsaRekey = 41,
        /// IKEv2 GSA_INBAND_REKEY. RFC 9838.
        GsaInbandRekey = 42,
        /// IKEv2 IKE_INTERMEDIATE. RFC 9242.
        IkeIntermediate = 43,
        /// IKEv2 IKE_FOLLOWUP_KE. RFC 9370.
        IkeFollowupKe = 44,
    }
}

/// Parsed ISAKMP/IKEv2 header.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct IkeHeader {
    /// Initiator's Security Parameter Index (SPI / cookie). 8 bytes.
    /// Generated by the initiator, must be non-zero. RFC 2408 section 3.1.
    pub initiator_spi: u64,
    /// Responder's SPI. Zero in the first message of an exchange.
    pub responder_spi: u64,
    /// Type of the first payload after this header. RFC 2408 section 3.1.
    pub next_payload: u8,
    /// Protocol version.
    pub version: IkeVersion,
    /// Exchange type (Main Mode, Aggressive, IKE_SA_INIT, etc.).
    pub exchange_type: ExchangeType,
    /// Flags byte. Interpretation differs between IKEv1 and IKEv2.
    ///
    /// IKEv1 (RFC 2408 section 3.1): bit 0 = Encryption, bit 1 = Commit, bit 2 = Auth-Only.
    /// IKEv2 (RFC 7296 section 3.1): bit 3 = Initiator, bit 4 = Version, bit 5 = Response.
    pub flags: u8,
    /// Message ID. Zero for IKEv1 Phase 1 and IKEv2 IKE_SA_INIT.
    pub message_id: u32,
    /// Total message length in bytes, including this 28-byte header.
    pub length: u32,
}

impl IkeHeader {
    /// Parse a 28-byte header from a buffer. Returns `None` if the buffer is
    /// shorter than [`HEADER_LEN`].
    #[must_use]
    pub fn parse(buf: &[u8]) -> Option<Self> {
        let b: &[u8; HEADER_LEN] = buf.get(..HEADER_LEN)?.try_into().ok()?;
        Some(Self {
            initiator_spi: u64::from_be_bytes([b[0], b[1], b[2], b[3], b[4], b[5], b[6], b[7]]),
            responder_spi: u64::from_be_bytes([b[8], b[9], b[10], b[11], b[12], b[13], b[14], b[15]]),
            next_payload: b[16],
            version: IkeVersion::from_byte(b[17]),
            exchange_type: ExchangeType::from(b[18]),
            flags: b[19],
            message_id: u32::from_be_bytes([b[20], b[21], b[22], b[23]]),
            length: u32::from_be_bytes([b[24], b[25], b[26], b[27]]),
        })
    }

    /// Serialize this header into a 28-byte buffer.
    #[must_use]
    pub fn to_bytes(self) -> [u8; HEADER_LEN] {
        let mut buf = [0u8; HEADER_LEN];
        buf[0..8].copy_from_slice(&self.initiator_spi.to_be_bytes());
        buf[8..16].copy_from_slice(&self.responder_spi.to_be_bytes());
        buf[16] = self.next_payload;
        buf[17] = self.version.to_byte();
        buf[18] = u8::from(self.exchange_type);
        buf[19] = self.flags;
        buf[20..24].copy_from_slice(&self.message_id.to_be_bytes());
        buf[24..28].copy_from_slice(&self.length.to_be_bytes());
        buf
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip() {
        let hdr = IkeHeader {
            initiator_spi: 0xDEAD_BEEF_CAFE_BABE,
            responder_spi: 0,
            next_payload: 1, // SA
            version: IkeVersion::V1,
            exchange_type: ExchangeType::Aggressive,
            flags: 0,
            message_id: 0,
            length: 28,
        };
        let bytes = hdr.to_bytes();
        let parsed = IkeHeader::parse(&bytes).expect("parse should succeed");
        assert_eq!(hdr, parsed);
    }

    #[test]
    fn ikev2_round_trip() {
        let hdr = IkeHeader {
            initiator_spi: 0x0102_0304_0506_0708,
            responder_spi: 0,
            next_payload: 33, // SA (IKEv2)
            version: IkeVersion::V2,
            exchange_type: ExchangeType::IkeSaInit,
            flags: 0x08, // Initiator flag. RFC 7296 section 3.1.
            message_id: 0,
            length: 300,
        };
        let bytes = hdr.to_bytes();
        let parsed = IkeHeader::parse(&bytes).expect("parse should succeed");
        assert_eq!(hdr, parsed);
    }

    #[test]
    fn short_buffer_returns_none() {
        let buf = [0u8; 27];
        assert!(IkeHeader::parse(&buf).is_none());
    }

    #[test]
    fn version_display() {
        assert_eq!(IkeVersion::V1.to_string(), "IKEv1");
        assert_eq!(IkeVersion::V2.to_string(), "IKEv2");
        assert_eq!(IkeVersion::Unknown(0x30).to_string(), "Unknown(0x30)");
    }

    #[test]
    fn exchange_type_round_trip_all_known() {
        for val in [1, 2, 3, 4, 5, 32, 33, 34, 35, 36, 37] {
            let et = ExchangeType::from(val);
            let back: u8 = et.into();
            assert_eq!(val, back, "round-trip failed for {val}");
        }
    }

    #[test]
    fn exchange_type_unknown_round_trip() {
        let et = ExchangeType::from(99);
        assert!(matches!(et, ExchangeType::Other(99)));
        let back: u8 = et.into();
        assert_eq!(back, 99);
    }
}
